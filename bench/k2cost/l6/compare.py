#!/usr/bin/env python3
"""L6 seal spike: acceptance tables (SPIKE-PLAN.md §3, review A6, C3).

  python3 compare.py --identity RUN_A RUN_B [--tol 0.05] [--out identity.json]
      Arm identity (§2.1, review A6): every billed Class A/B cell over the
      write-path window LT (load + tail, audits excluded, raw counts), the
      global PUT bytes over LT, and the mean RSS over the second half of the
      load, each within +-tol; and the effective posture of both runs.

  python3 compare.py --milestone M1 --census census.json --predict predict.json
                     --identity-json identity.json --out criteria.md
      M1's acceptance, one row per criterion and point.

Python 3.9 compatible, standard library only; imports census.py beside it.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import census as C  # noqa: E402

POSTURE_KEYS = ("INITIAL_SHARDS", "WAL_FLUSH_GAP_MS", "L6_SPILL", "TAIL_RING_BYTES", "ADMIT_RSS_SHED_MB",
                "PROJECT_MEMORY_PRESSURE_BYTES", "PROJECT_SHARE_K", "MAX_UNABSORBED_BYTES_PER_INSTANCE",
                "s3lite_latency_ms", "s3lite_put_bytes_per_sec")


def lt_billed_cells(run_dir):
    run = C.Run(run_dir)
    lt = C.window_delta(run, [(3, 3), (5, 5)])
    _, by_cell, tot = C.billed(lt["counts"])

    def gput(rec):
        return int((((rec or {}).get("s3lite") or {}).get("stats") or {}).get("put_bytes") or 0)
    put = sum(gput(run.b(p1, "end")) - gput(run.b(p0, "start")) for p0, p1 in [(3, 3), (5, 5)])
    return run, by_cell, tot, put, lt


def identity(a_dir, b_dir, tol):
    ra, ca, ta, pa, lta = lt_billed_cells(a_dir)
    rb, cb, tb, pb, ltb = lt_billed_cells(b_dir)
    sa, sb = C.census_run(a_dir), C.census_run(b_dir)
    rows, fails = [], []
    for key in sorted(set(ca) | set(cb)):
        for cls in ("A", "B"):
            x, y = ca.get(key, {}).get(cls, 0), cb.get(key, {}).get(cls, 0)
            if not x and not y:
                continue
            ratio = (y / x) if x else math.inf
            ok = abs(ratio - 1) <= tol if x else False
            # Poisson noise of the smaller count: above tol, the cell cannot resolve +-tol.
            noise = 1 / math.sqrt(min(x, y)) if min(x, y) > 0 else math.inf
            row = {"cell": key, "class": cls, "a": x, "b": y, "ratio": ratio if math.isfinite(ratio) else None,
                   "pass": ok, "poisson_1sigma": noise if math.isfinite(noise) else None, "noise_limited": noise > tol}
            rows.append(row)
            if not ok:
                fails.append(row)
    tot = {cls: {"a": ta[cls], "b": tb[cls], "ratio": tb[cls] / ta[cls] if ta[cls] else None} for cls in ("A", "B")}
    put = {"a": pa, "b": pb, "ratio": pb / pa if pa else None}
    put["pass"] = put["ratio"] is not None and abs(put["ratio"] - 1) <= tol
    rss_a, rss_b = sa["rss_mb"]["mean_second_half_load"], sb["rss_mb"]["mean_second_half_load"]
    rss = {"a": rss_a, "b": rss_b, "ratio": (rss_b / rss_a) if rss_a else None}
    rss["pass"] = rss["ratio"] is not None and abs(rss["ratio"] - 1) <= tol
    posture = {k: [sa["posture"].get(k), sb["posture"].get(k)] for k in POSTURE_KEYS}
    norm = lambda v: None if v in (None, "", 0, "0") else str(v)  # noqa: E731
    posture_diff = {k: v for k, v in posture.items() if norm(v[0]) != norm(v[1])}
    load = {k: [sa["load"].get(k), sb["load"].get(k)] for k in ("stored_bytes_S", "logical_bytes_L", "acked_requests",
                                                                  "c_L_over_S", "req_per_s")}
    return {"a": a_dir, "b": b_dir, "tol": tol, "window": "LT = load + tail (raw billed counts, audits excluded)",
            "cells": rows, "n_cells": len(rows), "n_fail": len(fails),
            "n_fail_not_noise_limited": len([f for f in fails if not f["noise_limited"]]),
            "totals": tot, "put_bytes_LT": put, "rss_mean_second_half_load_mb": rss,
            "posture": posture, "posture_diff": posture_diff, "load": load,
            "valid": [sa["validity"]["valid"], sb["validity"]["valid"]],
            "windows_s": [sa["windows_s"], sb["windows_s"]],
            "cpu_s_LT": [sa["cpu"]["server_cpu_s_LT"], sb["cpu"]["server_cpu_s_LT"]],
            "pass_cells": not fails, "pass": not fails and put["pass"] and rss["pass"] and not posture_diff}


def fmt(x, n=2):
    return ("%.*f" % (n, x)) if isinstance(x, (int, float)) and math.isfinite(x) else "-"


def m1(census, predict, ident):
    out = ["# M1 acceptance (generated by compare.py)", ""]
    runs = census["runs"]
    # 1. reconciliation
    out += ["## 1. Byte ledger: per-cell PUT bytes sum to the global put_bytes, live bytes reconcile, in every snapshot", "",
            "| point | snapshots checked | failures | pass |", "|---|---|---|---|"]
    all_ok = True
    for name, r in sorted(runs.items()):
        rc = r.get("reconciliation") or {}
        ok = bool(rc.get("ok"))
        all_ok &= ok
        out.append("| %s | %s | %s | %s |" % (name, rc.get("snapshots_checked"), rc.get("n_failures"), "yes" if ok else "**NO**"))
    out += ["", "All points: **%s**." % ("pass" if all_ok else "FAIL"), ""]
    # 2. identity
    if ident:
        out += ["## 2. Arm identity: instrumented build vs unmodified 50fab9d9 at b64rand 1 KiB x 10, 100 ms, uncapped", "",
                "A = `%s`, B = `%s`. Window: %s. Tolerance +-%d%%." % (os.path.basename(ident["a"]), os.path.basename(ident["b"]),
                                                                     ident["window"], round(ident["tol"] * 100)), "",
                "| cell | class | unmodified | instrumented | ratio | Poisson 1 sigma | pass |", "|---|---|---|---|---|---|---|"]
        for row in ident["cells"]:
            out.append("| %s | %s | %d | %d | %s | %s | %s |" % (row["cell"], row["class"], row["a"], row["b"], fmt(row["ratio"], 3),
                                                                 fmt(row["poisson_1sigma"], 3),
                                                                 "yes" if row["pass"] else ("no (noise-limited)" if row["noise_limited"] else "**NO**")))
        t = ident["totals"]
        out += ["", "Totals: Class A %d vs %d (ratio %s); Class B %d vs %d (ratio %s)." % (
            t["A"]["a"], t["A"]["b"], fmt(t["A"]["ratio"], 3), t["B"]["a"], t["B"]["b"], fmt(t["B"]["ratio"], 3)),
            "PUT bytes over LT: %d vs %d (ratio %s, %s)." % (ident["put_bytes_LT"]["a"], ident["put_bytes_LT"]["b"],
                                                           fmt(ident["put_bytes_LT"]["ratio"], 4), "pass" if ident["put_bytes_LT"]["pass"] else "FAIL"),
            "Mean RSS, second half of load: %s vs %s MB (ratio %s, %s; macOS RSS, indicative)." % (
                fmt(ident["rss_mean_second_half_load_mb"]["a"], 1), fmt(ident["rss_mean_second_half_load_mb"]["b"], 1),
                fmt(ident["rss_mean_second_half_load_mb"]["ratio"], 3), "pass" if ident["rss_mean_second_half_load_mb"]["pass"] else "FAIL"),
            "Server CPU over LT: %s vs %s s (indicative; macOS CPU seconds on a shared host)." % (
                fmt(ident["cpu_s_LT"][0], 1), fmt(ident["cpu_s_LT"][1], 1)),
            "Load: %s." % json.dumps(ident["load"]),
            "Posture differences: %s." % (json.dumps(ident["posture_diff"]) if ident["posture_diff"] else "none"),
            "Cells outside +-%d%%: %d of %d, of which %d not noise-limited." % (round(ident["tol"] * 100), ident["n_fail"], ident["n_cells"],
                                                                              ident["n_fail_not_noise_limited"]), ""]
    # 3. WAL ratio and shard + history
    out += ["## 3. Base WAL ratio vs 1 + 0.83-0.91 KB of rows / stored bytes per request (+-15%), and shard + history uploads 4-9", "",
            "| point | valid | S/req B | WAL measured | expected band | tolerance band | implied rows B/req | pass | shard+hist | (+WAL) | pass |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in sorted(runs.items()):
        w = r.get("wal_ratio_check") or {}
        s = r.get("shard_plus_hist_check") or {}
        if not w:
            out.append("| %s | %s | - | - | - | - | - | - | - | - | - |" % (name, (r.get("validity") or {}).get("valid")))
            continue
        out.append("| %s | %s | %s | %s | %s-%s | %s-%s | %s | %s | %s | %s | %s |" % (
            name, "yes" if r["validity"]["valid"] else "VOID", fmt(r["load"]["stored_bytes_per_request"], 0), fmt(w["measured"], 3),
            fmt(w["expected_band"][0], 3), fmt(w["expected_band"][1], 3), fmt(w["tolerance_band"][0], 3), fmt(w["tolerance_band"][1], 3),
            fmt(w["implied_row_bytes_per_request"], 0), "yes" if w["pass"] else "**NO**", fmt(s.get("measured")), fmt(s.get("with_wal")),
            "yes" if s.get("pass") else "**NO**"))
    # 4. predictions
    out += ["", "## 4. predict.json for every point", "", "| point | predict entry | per-run copy | today total (model) | measured total | B primary total | B window s |",
            "|---|---|---|---|---|---|---|"]
    for name, r in sorted(runs.items()):
        p = (predict or {}).get("points", {}).get(name)
        copy = os.path.exists(os.path.join(r.get("run", ""), "predict.json"))
        up = ((r.get("uploads_per_stored_byte") or {}).get("LT") or {}).get("total")
        if p and "today" in p:
            out.append("| %s | yes | %s | %s | %s | %s | %s |" % (name, "yes" if copy else "no", fmt(p["today"]["uploads_total"]), fmt(up),
                                                               fmt(p["design_b"]["primary"]["uploads_total"], 3),
                                                               fmt(p["design_b"]["primary"]["window_s"], 1)))
        else:
            out.append("| %s | **no** | %s | - | %s | - | - |" % (name, "yes" if copy else "no", fmt(up)))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--identity", nargs=2, metavar=("RUN_A", "RUN_B"))
    ap.add_argument("--tol", type=float, default=0.05)
    ap.add_argument("--milestone")
    ap.add_argument("--census")
    ap.add_argument("--predict")
    ap.add_argument("--identity-json")
    ap.add_argument("--out")
    a = ap.parse_args()
    if a.identity:
        doc = identity(a.identity[0], a.identity[1], a.tol)
        text = json.dumps(doc, indent=1, sort_keys=True)
        if a.out:
            with open(a.out, "w", encoding="utf-8") as f:
                f.write(text + "\n")
        print("identity: cells %d, outside tol %d (%d not noise-limited); put bytes ratio %s; rss ratio %s; posture diff %s; pass %s"
              % (doc["n_cells"], doc["n_fail"], doc["n_fail_not_noise_limited"], fmt(doc["put_bytes_LT"]["ratio"], 4),
                 fmt(doc["rss_mean_second_half_load_mb"]["ratio"], 3), doc["posture_diff"] or "none", doc["pass"]))
        return 0
    if a.milestone == "M1":
        with open(a.census, encoding="utf-8") as f:
            census = json.load(f)
        predict = json.load(open(a.predict, encoding="utf-8")) if a.predict and os.path.exists(a.predict) else None
        ident = json.load(open(a.identity_json, encoding="utf-8")) if a.identity_json and os.path.exists(a.identity_json) else None
        text = m1(census, predict, ident)
        if a.out:
            with open(a.out, "w", encoding="utf-8") as f:
                f.write(text)
        print(text)
        return 0
    ap.error("give --identity or --milestone M1")


if __name__ == "__main__":
    sys.exit(main())
